export async function writeAiArtifact(directory: string, name: string, contents: string): Promise<string> {
  const path = join(directory, name);
  await mkdir(dirname(path), { recursive: true });
  await writeFile(path, contents, { encoding: "utf8", mode: 0o600 });
  return path;
}

export function renderBrief(
  site: string,
  triage: TriageResult,
  provider: AiProviderInfo
): string {
  const rows = triage.workOrder
    .map(
      (item) =>
        `| ${item.rank} | ${markdownCell(item.title)} | ${item.findingCount} | ${item.effort} | ${item.owner} | ${markdownCell(item.whyFirst)} |`
    )
    .join("\n");
  const actions = triage.workOrder
    .map((item) => `${item.rank}. **${markdownCell(item.title)}** — ${markdownCell(item.action)}`)
    .join("\n");
  const risks = triage.risks.map((risk) => `- ${markdownCell(risk)}`).join("\n");
  const questions = triage.questions.map((question) => `- ${markdownCell(question)}`).join("\n");

  return `# Migration brief — ${markdownCell(site)}

Generated by ${packageName} ${packageVersion} using ${provider.model} at ${provider.endpoint}. This is a proposal for review; it is not a migration result.

## Summary

${markdownCell(triage.summary)}

## Proposed work order

| # | Work | Findings | Effort | Owner | Why first |
| --- | --- | ---: | --- | --- | --- |
${rows}

## Actions

${actions}

## Risks to keep visible

${risks || "- No additional risks were proposed."}

## Questions before content work

${questions || "- None."}

## What this brief does not decide

The model did not read post bodies for this triage. It worked from the finding queue and the plan counts. Severity, waivers, routes and launch gates stay deterministic and human-controlled. Use this work order to plan the migration. Run the alt-text, shortcodes, routes or repair job to produce reviewable decisions, then rebuild with the accepted decisions before treating the migration as complete.
`;
}

