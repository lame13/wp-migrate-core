function renderTriageReview(triage: TriageResult): string {
  return `<h2>Proposed work order</h2>
<table>
  <thead><tr><th>#</th><th>Work</th><th>Findings</th><th>Effort</th><th>Owner</th><th>Why first</th></tr></thead>
  <tbody>
    ${triage.workOrder
      .map(
        (item) =>
          `<tr><td>${item.rank}</td><td><strong>${escapeHtml(item.title)}</strong><br><span class="muted">${escapeHtml(item.action)}</span></td><td>${item.findingCount}</td><td>${escapeHtml(item.effort)}</td><td>${escapeHtml(item.owner)}</td><td>${escapeHtml(item.whyFirst)}</td></tr>`
      )
      .join("\n")}
  </tbody>
</table>
<div class="panel"><h2>Risks</h2><ul>${triage.risks.map((risk) => `<li>${escapeHtml(risk)}</li>`).join("")}</ul></div>
<div class="panel"><h2>Questions</h2><ul>${triage.questions.map((question) => `<li>${escapeHtml(question)}</li>`).join("")}</ul></div>`;
}

function renderItemTable(items: readonly AiSuggestion[]): string {
  return `<h2>Suggestions</h2>
<table>
  <thead><tr><th>Kind</th><th>Subject</th><th>Proposal</th><th>Confidence</th><th>Reason</th></tr></thead>
  <tbody>
    ${items
      .map((item) => {
        const cls = item.status === "rejected" ? ' class="rejected"' : "";
        return `<tr${cls}><td><span class="badge">${escapeHtml(item.kind)}${item.status === "rejected" ? " · rejected" : ""}</span></td><td>${escapeHtml(subject(item))}</td><td>${escapeHtml(proposal(item))}</td><td>${escapeHtml(confidence(item))}</td><td>${escapeHtml(item.reason ?? "")}</td></tr>`;
      })
      .join("\n")}
  </tbody>
</table>`;
}

function subject(item: AiSuggestion): string {
  if (item.kind === "alt-text") return item.assetId;
  if (item.kind === "mapping") return item.key;
  if (item.kind === "route") return item.source;
  return item.sourceId;
}

function proposal(item: AiSuggestion): string {
  if (item.kind === "alt-text") {
    return item.decorative ? "(decorative: empty alt)" : item.value;
  }
  if (item.kind === "mapping") {
    return item.strategy === "static-fallback"
      ? `static fallback: ${item.fallbackText ?? ""}`
      : item.strategy === "component"
        ? `component: ${item.component ?? ""}`
        : item.strategy;
  }
  if (item.kind === "route") {
    return `${item.targetRoute} (score ${item.score}; alternatives: ${item.alternatives
      .slice(1, 4)
      .map((candidate) => `${candidate.route} ${candidate.score}`)
      .join(", ") || "none"})`;
  }
  return item.repairedHtml.length === 0
    ? "No safe patch"
    : `${item.changes.length} change${item.changes.length === 1 ? "" : "s"}`;
}

function confidence(item: AiSuggestion): string {
  return "confidence" in item ? item.confidence : "";
}

function jobLabel(job: AiJob): string {
  if (job === "alt-text") return "alt text";
  if (job === "shortcodes") return "shortcode and widget mapping";
  if (job === "routes") return "route matching";
  return job;
}

function markdownCell(value: string): string {
  return value.replace(/\|/g, "\\|").replace(/\n+/g, " ").trim();
}
